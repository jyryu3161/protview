#!/usr/bin/env python3
"""Write the labeled synthetic M12 pocket-QA invalid inputs and check their pinned SHA-256.

Every file is SYNTHETIC (idealized alanine-like heavy-atom offsets, the same geometry rule as
backend/tests/test_pockets.py); none is an observed structure and none carries a scientific result.
They exist only so the offscreen QA can show a pocket-detection input rejection before any job:

- ``m12-synthetic-modified-residue.pdb``: three ALA residues plus one ``CYX`` residue written as ATOM
  (a modified amino-acid name outside the 20 standard residues and the six histidine aliases);
  expected preflight rejection ``modified_residue_unsupported``.
- ``m12-synthetic-degenerate-collinear.pdb``: six GLY residues holding only a CA atom on one line
  (coordinate rank 1); expected preflight rejection ``degenerate_geometry``.

``m12-invalid-cases.json`` lists each file, its SHA-256, its label and the expected reason code (the
code follows from the edit made here, not from running the product). If any generated byte differs
from the pinned SHA-256 nothing is written and the script exits non-zero. Runtime never calls this.

Usage: .venv/bin/python scripts/m12_qa_inputs.py --out <dir>
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ALA = [("N", "N", (0.0, 0.0, 0.0)), ("CA", "C", (1.458, 0.0, 0.0)), ("C", "C", (2.009, 1.42, 0.0)),
       ("O", "O", (1.251, 2.39, 0.0)), ("CB", "C", (1.988, -0.773, -1.199))]
LABEL = "labeled synthetic M12 invalid-input control (idealized geometry; not an observed structure)"
PINNED = {
    "m12-synthetic-modified-residue.pdb": "f742043fb46deb39a41ca5d0d3da1fee5d518fb7c8f706ab7518d26cb685e006",
    "m12-synthetic-degenerate-collinear.pdb": "a25a960c543218056279e9da1cc00451a9706b9134d056ec225109643ed57f91",
}


def _line(serial: int, name: str, resname: str, chain: str, resseq: int, xyz, element: str,
          record: str = "ATOM") -> str:
    field = f" {name:<3}" if len(name) < 4 and len(element) == 1 else f"{name:<4}"
    return (f"{record:<6}{serial:5d} {field} {resname:>3} {chain}{resseq:4d}    "
            f"{xyz[0]:8.3f}{xyz[1]:8.3f}{xyz[2]:8.3f}{1.0:6.2f}{10.0:6.2f}          {element:>2}  ")


def _pdb(residues: list[tuple[str, int, list[tuple[str, str, tuple[float, float, float]]]]]) -> bytes:
    lines, serial = [], 1
    for resname, seq, atoms in residues:
        for name, element, xyz in atoms:
            lines.append(_line(serial, name, resname, "A", seq, xyz, element))
            serial += 1
    return ("\n".join(lines) + "\nEND\n").encode()


def _ala(seq: int, offset: tuple[float, float, float], resname: str = "ALA"):
    return (resname, seq, [(n, e, tuple(a + b for a, b in zip(xyz, offset))) for n, e, xyz in ALA])


def build() -> dict[str, tuple[bytes, str, str]]:
    offsets = [(4.0 * i, 0.3 * i, 0.1 * i * i) for i in range(4)]
    modified = _pdb([_ala(i + 1, offsets[i]) for i in range(3)] + [_ala(4, offsets[3], "CYX")])
    collinear = _pdb([("GLY", i, [("CA", "C", (3.8 * i, 0.0, 0.0))]) for i in range(1, 7)])
    return {
        "m12-synthetic-modified-residue.pdb": (
            modified, "modified_residue_unsupported",
            "three ALA plus one CYX (ATOM) residue in chain A; CYX is not a supported standard/histidine name"),
        "m12-synthetic-degenerate-collinear.pdb": (
            collinear, "degenerate_geometry", "six collinear GLY CA atoms (coordinate rank 1)"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--print-hashes", action="store_true", help="print generated SHA-256 values and exit")
    args = parser.parse_args()
    built = build()
    digests = {name: hashlib.sha256(raw).hexdigest() for name, (raw, _, _) in built.items()}
    if args.print_hashes:
        print(json.dumps(digests, indent=2))
        return 0
    wrong = {name: digest for name, digest in digests.items() if PINNED[name] != digest}
    if wrong:
        print(json.dumps({"error": "generated bytes differ from pinned SHA-256", "generated": wrong}), file=sys.stderr)
        return 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    cases = []
    for name, (raw, code, edit) in built.items():
        (out / name).write_bytes(raw)
        cases.append({"file": name, "sha256": digests[name], "bytes": len(raw), "label": LABEL,
                      "edit": edit, "expected_reason_code": code})
    manifest = {"schema": "m12_invalid_cases@1", "generator": "scripts/m12_qa_inputs.py", "cases": cases}
    (out / "m12-invalid-cases.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"out": str(out), "files": [case["file"] for case in cases]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
