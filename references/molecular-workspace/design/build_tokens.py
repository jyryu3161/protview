"""design/tokens.json -> frontend/src/design/tokens.css  (run after every token edit)

    python design/build_tokens.py
Themes: first theme is the default on :root; others via [data-theme="<id>"].
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
t = json.loads((HERE / "tokens.json").read_text())
themes = [x["id"] for x in t["color"]["themes"]]


def val(v, theme):
    x = v[theme] if isinstance(v, dict) else v
    return f"var(--{x[1:-1]})" if x.startswith("{") else x


out = ["/* GENERATED from design/tokens.json by design/build_tokens.py — do not edit */"]
for i, th in enumerate(themes):
    sel = f':root, [data-theme="{th}"]' if i == 0 else f'[data-theme="{th}"]'
    lines = [f"  --{c['name']}: {val(c['value'], th)};" for c in t["color"]["tokens"]]
    lines += [f"  --{s['name']}: {val(s['value'], th)};" for s in t.get("shadow", {}).get("tokens", [])]
    lines.append(f"  color-scheme: {th};")
    out.append(sel + " {\n" + "\n".join(lines) + "\n}")
root = []
for fam in ("spacing", "radius", "size"):
    root += [f"  --{x['name']}: {x['value']};" for x in t.get(fam, {}).get("tokens", [])]
root += [f"  --font-{k}: {v};" for k, v in t["type"]["families"].items()]
out.append(":root {\n" + "\n".join(root) + "\n}")
for g in t["type"]["groups"]:
    for s in g["styles"]:
        fam = s.get("family", g["family"])
        decl = [f"font-family: var(--font-{fam})", f"font-size: {s['fontSize']}", f"line-height: {s['lineHeight']}",
                f"font-weight: {s['fontWeight']}"] + ([f"letter-spacing: {s['letterSpacing']}"] if "letterSpacing" in s else [])
        out.append(f".t-{s['name']} {{ {'; '.join(decl)}; }}")
dst = HERE.parent / "frontend/src/design/tokens.css"
dst.write_text("\n\n".join(out) + "\n")
# also a TS list of token names for type-safe color props
names = [c["name"] for c in t["color"]["tokens"]]
(HERE.parent / "frontend/src/design/tokens.ts").write_text(
    "// GENERATED by design/build_tokens.py — do not edit\n"
    f"export const colorTokens = {json.dumps(names)} as const;\n"
    "export type ColorToken = (typeof colorTokens)[number];\n"
    "export const cssVar = (t: ColorToken) => `var(--${t})`;\n")
print("wrote", dst)

# components.css -> frontend copy WITHOUT the Google Fonts @import:
# the app is local-first; fonts are self-hosted via @fontsource (see frontend/app/layout.tsx).
css = (HERE / "components.css").read_text()
css = "\n".join(l for l in css.splitlines() if not l.startswith("@import url('https://fonts.googleapis.com"))
(HERE.parent / "frontend/src/design/components.css").write_text(
    "/* COPIED from design/components.css by design/build_tokens.py — edit the source, not this file */\n" + css + "\n")
print("copied components.css")
